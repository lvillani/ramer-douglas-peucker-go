// Generates Swift code to construct a CoreGraphics CGPath from GeoJSON polygon data.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"io/ioutil"
	"log"
	"os"
	"strings"
	"text/template"

	rdp "github.com/lvillani/ramer-douglas-peucker-go"
)

var epsilon = flag.Float64("epsilon", 0.006, "")

var swiftTemplate = strings.TrimSpace(`
// Generated by geojson2cgpath from https://github.com/lvillani/ramer-douglas-peucker-go
//
// There are {{.PointsLen}} points in this path.
let path = CGMutablePath()

path.move(to: CGPoint(x: {{.StartX}}, y: {{.StartY}}))
{{range .Points}}
path.addLine(to: CGPoint(x: {{.X}}, y: {{.Y}}))
{{- end}}

path.closeSubpath()
`)

type collection struct {
	Geometries []polygon `json:"geometries"`
	Type       string    `json:"type"`
}

type polygon struct {
	Coordinates [][][][]float64 `json:"coordinates"`
	Type        string          `json:"type"`
}

func main() {
	flag.Parse()

	if len(flag.Args()) != 1 {
		log.Fatalln("usage: <input file>")
	}

	p, err := slurp(flag.Args()[0])
	if err != nil {
		log.Fatalln(err)
	}

	points := coordinates2points(p.Coordinates[0][0])
	result := rdp.RamerDouglasPeucker(points[0:len(points)-1], *epsilon)

	swift, err := points2swift(result)
	if err != nil {
		log.Fatalln(err)
	}

	fmt.Println(swift)
}

func slurp(path string) (*polygon, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	buf, err := ioutil.ReadAll(f)
	if err != nil {
		return nil, err
	}

	collection := collection{}
	if err := json.Unmarshal(buf, &collection); err != nil {
		return nil, err
	}

	if len(collection.Geometries) != 1 {
		return nil, fmt.Errorf("expected one geometry, found %v", len(collection.Geometries))
	}

	return &collection.Geometries[0], nil
}

func coordinates2points(points [][]float64) []rdp.Point {
	var ret []rdp.Point

	for _, v := range points {
		ret = append(ret, rdp.Point{X: v[0], Y: v[1]})
	}

	return ret
}

func points2swift(pp []rdp.Point) (string, error) {
	if len(pp) < 3 {
		return "", fmt.Errorf("need at least three points to define a polygon")
	}

	t := template.Must(template.New("swift").Parse(swiftTemplate))

	var buf bytes.Buffer
	var err = t.Execute(&buf, struct {
		Points    []rdp.Point
		PointsLen int
		StartX    float64
		StartY    float64
	}{
		Points:    pp[1:],
		PointsLen: len(pp),
		StartX:    pp[0].X,
		StartY:    pp[0].Y,
	})

	if err != nil {
		return "", err
	}

	return string(buf.Bytes()), nil
}
